// 화면 주소 → 도움말 주제
export function topicForHash(hash = location.hash) {
  const parts = hash.replace(/^#\/?/, '').split('?')[0].split('/');
  switch (parts[0]) {
    case 'folders': case 'folder': return 'folder';
    case 'list': return { character: 'wiki', world: 'wiki', story: 'story', plot: 'plot' }[parts[1]] || 'start';
    case 'w': return parts[2] === 'edit' ? 'wiki-edit' : 'wiki';
    case 's': return 'story';
    case 'read': return 'reader';
    case 'p': return 'plot';
    case 'memo': return 'memo';
    case 'tools': return 'tools';
    case 'bookmarks': case 'search': return 'search';
    case 'settings': return 'settings';
    default: return 'start';
  }
}

// 다른 도움말로 옮겨갈 때 보이는 순서
const ORDER = ['start', 'folder', 'wiki', 'wiki-edit', 'story', 'editor', 'reader', 'export', 'plot', 'memo', 'tools', 'search', 'vault', 'settings'];

function topicHTML(key) {
  const t = HELP[key] || HELP.start;
  return `<div class="help-topic">
    <div class="help-title"><span class="help-ic">${icon(t.icon, 20)}</span><h4>${esc(t.title)}</h4></div>
    <p class="help-intro">${t.intro}</p>
    ${t.sections.map(([h, items]) => `<section class="help-sec"><h5>${esc(h)}</h5><ul>${items.map((x) => `<li>${x}</li>`).join('')}</ul></section>`).join('')}
  </div>`;
}

export function openHelp(key) {
  let cur = HELP[key] ? key : 'start';
  return modal({
    title: '도움말',
    body: `<div class="help-body" id="help-body">${topicHTML(cur)}</div>
      <div class="help-more"><span class="muted small">다른 도움말</span><div class="chip-row" id="help-chips">${ORDER.map((k) => `<button type="button" class="fchip ${k === cur ? 'on' : ''}" data-topic="${k}">${esc(HELP[k].title)}</button>`).join('')}</div></div>`,
    onOpen: (w) => {
      w.querySelector('#help-chips').addEventListener('click', (e) => {
        const b = e.target.closest('[data-topic]'); if (!b) return;
        cur = b.dataset.topic;
        w.querySelector('#help-body').innerHTML = topicHTML(cur);
        w.querySelectorAll('[data-topic]').forEach((x) => x.classList.toggle('on', x === b));
        w.querySelector('.modal-body').scrollTop = 0;
      });
    },
  });
}

// '?' 버튼 HTML. 페이지 어디에 넣어도 눌리면 해당 도움말이 열림
export function helpBtn(key, { label = '도움말', cls = '' } = {}) {
  const t = HELP[key];
  const name = t ? `${t.title} ${label}` : label;
  return `<button type="button" class="icon-btn sm help-btn ${cls}" data-help="${esc(key)}" title="${esc(name)}" aria-label="${esc(name)}">${icon('circle-question-mark', 18)}</button>`;
}

let installed = false;
export function installHelp() {
  if (installed) return;
  installed = true;
  document.addEventListener('click', (e) => {
    const b = e.target.closest('[data-help]');
    if (!b) return;
    e.preventDefault();
    e.stopPropagation();
    openHelp(b.dataset.help);
  }, true);
}
